def check_password_strength(pwd):
    score = 0
    if len(pwd) >= 8: score += 1
    if len(pwd) >= 12: score += 1
    if any(c.isupper() for c in pwd): score += 1
    if any(c.isdigit() for c in pwd): score += 1
    if any(not c.isalnum() for c in pwd): score += 1
    return score, {0:"Very Weak",1:"Weak",2:"Fair",3:"Good",4:"Strong",5:"Very Strong"}[score]

def generate_wordlist(name):
    words = []
    name_lower = name.lower()
    years = ["2020","2021","2022","2023","2024","2025","2026","123","!","@","#","1234","01"]
    prefixes = ["", name_lower, name_lower.capitalize(), name_lower.upper()]
    for p in prefixes:
        for y in years:
            words.append(f"{p}{y}")
            words.append(f"{p}{y}!")
            words.append(f"{p}!{y}")
            words.append(f"{p}_{y}")
            words.append(f"{y}{p}")
    return words[:100]



