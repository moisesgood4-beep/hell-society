def clear(): os.system('clear' if os.name!='nt' else 'cls')

def get_profile(username):
    try:
        r = requests.get(f"https://api.github.com/users/{username}", timeout=10)
        return r.json() if r.status_code == 200 else None
    except: return None

def get_repos(username):
    try:
        r = requests.get(f"https://api.github.com/users/{username}/repos?sort=updated&per_page=10", timeout=10)
        return r.json() if r.status_code == 200 else []
    except: return []

def search_code(username):
    try:
        r = requests.get(f"https://api.github.com/search/code?q={username}&per_page=5", timeout=10)
        return r.json().get("items", []) if r.status_code == 200 else []
    except: return []

